#!/usr/bin/env node
'use strict';
/**
 * Regenerates api/_lib/stages.js (the server-side price table) from assets/data.js and assets/data.en.js,
 * so the amounts the server charges always come from the same source as the prices shown on the site.
 *
 *   node scripts/build-stages.js
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const load = (file) => new Function(`${fs.readFileSync(path.join(root, 'assets', file), 'utf8')}; return TRACKS;`)();
const arabic = load('data.js');
const english = load('data.en.js');

const stages = {};
arabic.forEach((track, t) => track.stages.forEach((stage, s) => {
  const en = english[t].stages[s];
  if (en.id !== stage.id) throw new Error(`Stage order differs between the languages at ${stage.id}`);
  stages[stage.id] = {
    track: track.name, name: stage.name,
    track_en: english[t].name, name_en: en.name,
    fee: stage.fee, altFee: stage.alt ? stage.alt.fee : null,
  };
}));

const header = "'use strict';\n\n/** GENERATED by scripts/build-stages.js from assets/data.js and assets/data.en.js. Do not edit by hand. */\n";
fs.writeFileSync(path.join(root, 'api/_lib/stages.js'), `${header}module.exports = ${JSON.stringify(stages, null, 2)};\n`);
console.log(`stages.js written (${Object.keys(stages).length} stages)`);
